# DAY 1 — 30 Days of Python

# 1. Print simple text
print("Hello World!")
print("Welcome to 30 Days of Python")

# 2. Basic math operations
print("Addition:", 5 + 3)
print("Subtraction:", 10 - 4)
print("Multiplication:", 6 * 2)
print("Division:", 8 / 2)

# 3. Variables
name = "Ahmad"
country = "Nigeria"
city = "Abuja"

print("My name is", name)
print("I live in", city, country)

# 4. Data types
print(type(name))      # string
print(type(10))        # integer
print(type(3.14))      # float
print(type(True))      # boolean

# 5. String operations
first_name = "Ahmad"
last_name = "Aliyu"
full_name = first_name + " " + last_name

print("Full name:", full_name)
print("Length of name:", len(full_name))

# 6. User input
age = input("Enter your age: ")
print("You are", age, "years old")

print("Day 1 completed 🎉")
