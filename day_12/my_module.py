def generate_full_name(firstname, lastname):
    return firstname + " " + lastname

def sum_two_nums(a, b):
    return a + b

def person_info(firstname, lastname, country, age):
    return f"{firstname} {lastname} lives in {country}. He is {age} years old."

def add_all_nums(*nums):
    return sum(nums)